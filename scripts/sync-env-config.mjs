#!/usr/bin/env node
/**
 * Writes public/env-config.js from .env.local so CONFIG_ID is available
 * in the browser before the Next.js bundle loads (local dev).
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const envPath = path.join(root, '.env.local');
const outPath = path.join(root, 'public', 'env-config.js');

function parseEnvFile(filePath) {
  if (!fs.existsSync(filePath)) return {};
  const vars = {};
  for (const line of fs.readFileSync(filePath, 'utf8').split('\n')) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;
    const eq = trimmed.indexOf('=');
    if (eq === -1) continue;
    const key = trimmed.slice(0, eq).trim();
    let value = trimmed.slice(eq + 1).trim();
    if ((value.startsWith('"') && value.endsWith('"')) || (value.startsWith("'") && value.endsWith("'"))) {
      value = value.slice(1, -1);
    }
    vars[key] = value;
  }
  return vars;
}

const env = parseEnvFile(envPath);
const configId =
  env.NEXT_PUBLIC_CONFIG_ID ||
  env.CONFIG_ID ||
  'MEDIUM';

const contents = `// Generated by scripts/sync-env-config.mjs — do not edit by hand
window._env_ = {
  CONFIG_ID: ${JSON.stringify(configId)}
};
`;

fs.writeFileSync(outPath, contents);
console.log(`Wrote ${outPath} with CONFIG_ID=${configId}`);
